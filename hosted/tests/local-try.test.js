import test from 'node:test';
import assert from 'node:assert/strict';
import {readFile,mkdtemp,writeFile,rm} from 'node:fs/promises';
import os from 'node:os';
import path from 'node:path';
import {pathToFileURL} from 'node:url';
test('browser module uses original core; no input transport; bounds',async()=>{
 const dir=await mkdtemp(path.join(os.tmpdir(),'local-try-'));
 try {
 const tool=await readFile(new URL('../public/try.js',import.meta.url),'utf8');
 assert.doesNotMatch(tool,/\b(fetch|XMLHttpRequest|sendBeacon|WebSocket|localStorage|sessionStorage)\b/);
 await writeFile(path.join(dir,'package.json'),'{"type":"module"}');
 await writeFile(path.join(dir,'tool.js'),tool);
 await writeFile(path.join(dir,'core.js'),await readFile(new URL('../../src/index.js',import.meta.url)));
 await writeFile(path.join(dir,'strict-json.js'),await readFile(new URL('../../src/strict-json.js',import.meta.url)));
 const {check,readLocalText}=await import(pathToFileURL(path.join(dir,'tool.js')));
 const json='{\n  "items": [\n    {"qty":0},\n    {}\n  ]\n}';
 const rules=JSON.stringify({type:'object',properties:{items:{type:'array',items:{type:'object',required:['qty'],properties:{qty:{type:'integer',minimum:1}}}}}});
 const located=check({value:json,schema:rules});
 assert.equal(located.errors.length,2);
 const bad=located.errors.find(x=>x.code==='BELOW_MINIMUM');
 const missing=located.errors.find(x=>x.code==='REQUIRED');
 assert.deepEqual(bad.location,{line:3,column:12,offset:json.indexOf('0}'),kind:'value'});
 assert.deepEqual(missing.location,{line:4,column:5,offset:json.indexOf('{}'),kind:'parent'});
 const hintRules=JSON.stringify({type:'object',additionalProperties:false,properties:{email:{type:'string'},name:{type:'string'}}});
 const typo=check({value:'{"emali":"PRIVATE_SENTINEL"}',schema:hintRules});
 assert.equal(typo.errors[0].suggestedKey,'email');
 assert.doesNotMatch(JSON.stringify(typo),/PRIVATE_SENTINEL/);
 assert.equal(check({value:'{"emali":"x","email":"y"}',schema:hintRules}).errors[0].suggestedKey,undefined);
 const ambiguous=JSON.stringify({type:'object',additionalProperties:false,properties:{cat:{type:'string'},bat:{type:'string'}}});
 assert.equal(check({value:'{"hat":"x"}',schema:ambiguous}).errors[0].suggestedKey,undefined);
 const nested=JSON.stringify({type:'array',items:{type:'object',additionalProperties:false,properties:{email:{type:'string'}}}});
 assert.equal(check({value:'[{"emai":"x"}]',schema:nested}).errors[0].suggestedKey,'email');
 const schemaFailure=check({value:json,schema:'{"type":"object","unsupported":true}'});
 assert.equal(schemaFailure.valid,false);assert.equal(schemaFailure.errors[0].location,undefined);
 assert.equal(check({value:'{"email":"bad"}',schema:'{"type":"object","properties":{"email":{"type":"string","format":"email"}}}'}).valid,false);
  assert.equal(check({value:'{"email":"user@example.com"}',schema:'{"type":"object","properties":{"email":{"type":"string","format":"email"}}}'}).valid,true);
 assert.throws(()=>check({value:'{"x":1,"x":2}',schema:'{"type":"object"}'}),SyntaxError);
 assert.throws(()=>check({value:'{"x":1,"\\u0078":2}',schema:'{"type":"object"}'}),SyntaxError);
 assert.throws(()=>check({value:'1',schema:'{"type":"number","type":"integer"}'}),SyntaxError);
 assert.throws(()=>check({value:'1e999',schema:'{"type":"number"}'}),RangeError);
 assert.throws(()=>check({value:'['.repeat(66)+'0'+']'.repeat(66),schema:'{"type":"array"}'}),RangeError);
 assert.equal(check({value:'{"x":"a\\\\b"}',schema:'{"type":"object","properties":{"x":{"type":"string"}}}'}).valid,true);
 assert.throws(()=>check({value:'x'.repeat(65537),schema:'{}',mode:'single',format:'email'}),RangeError);
 assert.throws(()=>check({value:'한'.repeat(22000),schema:'{}',mode:'single',format:'email'}),RangeError);
 assert.equal(await readLocalText(new Blob(['한글'])), '한글');
 await assert.rejects(()=>readLocalText(new Blob([new Uint8Array([0xff])])),TypeError);
 await assert.rejects(()=>readLocalText({size:65537,arrayBuffer(){throw Error('must not read oversized file');}}),RangeError);
 await assert.rejects(()=>readLocalText({size:1,arrayBuffer:async()=>new ArrayBuffer(2)}),RangeError);
 assert.equal((await readLocalText(new Blob(['x'.repeat(65536)]))).length,65536);
 } finally {await rm(dir,{recursive:true,force:true});}
});
